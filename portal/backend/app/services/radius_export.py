"""Write the FreeRADIUS users file from the database. The radius container reloads it on change."""

import time

from sqlalchemy.orm import Session

from app.core.config import Settings
from app.core.files import atomic_write
from app.repositories.wifi_users import WifiUserRepository

HEADER = "# Generated by the Wi-Fi portal - don't edit by hand; changes here are overwritten."


def radius_expiration(epoch: int) -> str:
    """FreeRADIUS Expiration value. The radius container runs in UTC, so the time is written in UTC."""
    return time.strftime("%b %d %Y %H:%M:%S", time.gmtime(epoch))


def users_line(username: str, nt_hash: str, expires_at: int | None) -> str:
    line = f"{username} NT-Password := 0x{nt_hash}"
    if expires_at is not None:
        line += f', Expiration := "{radius_expiration(expires_at)}"'
    return line


class RadiusUsersExporter:
    def __init__(self, settings: Settings):
        self.settings = settings

    def export(self, db: Session) -> None:
        lines = [HEADER] + [users_line(*row) for row in WifiUserRepository(db).enabled_credentials()]
        atomic_write(self.settings.users_file, "\n".join(lines) + "\n")
