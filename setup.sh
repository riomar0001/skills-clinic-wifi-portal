#!/bin/sh
# One-time setup for Linux (e.g. a Raspberry Pi). Same steps as setup.ps1 on Windows:
# creates the certificate, the router secret and an empty user list, then starts both containers.
# Safe to run again: it never replaces what already exists.
set -eu

cd "$(dirname "$0")"
image=freeradius/freeradius-server:3.2.8
server_name=wifi.skillsclinic.local
data=$PWD/data
certs=$data/certs

docker version --format '{{.Server.Version}}' >/dev/null
mkdir -p "$certs"
# Optional publicly trusted certificate (docs/SETUP.md): the certs container waits until
# letsencrypt/cloudflare.ini and letsencrypt/domain exist, and writes data/letsencrypt.
# Made here so Docker doesn't create them owned by root; the token folder is private.
mkdir -p letsencrypt "$data/letsencrypt"
chmod 700 letsencrypt

# Certificates: phones remember this one, so it is created once and kept (valid 10 years).
if [ ! -e "$certs/server.pem" ]; then
    echo 'Creating certificates...'
    docker run --rm -v "$certs:/out" --entrypoint sh "$image" -c "
        set -eu
        cd /etc/raddb/certs
        cp Makefile ca.cnf server.cnf client.cnf inner-server.cnf xpextensions /out/
        cd /out
        sed -i 's/^default_days.*/default_days = 3650/' ca.cnf server.cnf
        sed -i 's/Example Inc\./Skills Clinic/; s/example\.org/skillsclinic.local/' ca.cnf server.cnf
        sed -i 's/\"Example Certificate Authority\"/\"Skills Clinic WiFi CA\"/' ca.cnf
        sed -i 's/\"Example Server Certificate\"/\"$server_name\"/; s/^DNS\.1 = .*/DNS.1 = $server_name/' server.cnf
        make index.txt serial ca server >/dev/null
        test -s server.pem && test -s ca.pem && test -s ca.der
        chown -R $(id -u):$(id -g) /out"
fi

# Shared secret between the router and this server: 24 random letters and digits.
if [ ! -e "$data/clients.conf" ]; then
    secret=$(LC_ALL=C tr -dc 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789' </dev/urandom | head -c 24)
    [ ${#secret} -eq 24 ] || { echo 'Could not generate the router secret.' >&2; exit 1; }
    umask 077
    cat >"$data/clients.conf" <<EOF
# The TP-Link router. Any address is accepted here; the firewall limits who can reach port 1812.
client router {
	ipaddr = 0.0.0.0/0
	proto = udp
	secret = $secret
	require_message_authenticator = yes
}
EOF
    umask 022
fi

if [ ! -e "$data/users" ]; then
    # The portal fills this in from its database; FreeRADIUS needs the file to exist at start.
    printf '# Generated by the Wi-Fi portal.\n' >"$data/users"
fi

# The portal runs as UID 1000 and writes data/users; make sure it can.
if [ "$(id -u)" != 1000 ]; then
    echo "Note: the portal container runs as UID 1000. If it can't write $data, run: sudo chown -R 1000:1000 $data"
fi

docker compose up -d --build

echo
echo 'Running:'
echo '  Login server   UDP 1812 (for the router)'
if [ -e letsencrypt/cloudflare.ini ] && [ -e letsencrypt/domain ]; then
    domain=$(head -n 1 letsencrypt/domain | tr -d ' \r\n' | tr 'A-Z' 'a-z')
    echo "  Portal         https://$domain  (once the certificate is issued; http://<this machine> until then)"
    echo "  Certificate    Let's Encrypt, renewed automatically (docker logs wifi-certs)"
else
    echo '  Portal         http://<this machine>  (one sign-in for admins and Wi-Fi users)'
    echo '  Certificate    self-made (for a publicly trusted one, see docs/SETUP.md)'
fi

# The portal writes the first-admin setup code a few seconds after it starts.
i=0
while [ $i -lt 30 ] && [ ! -e "$data/setup-code.txt" ]; do
    # Asked inside the container: the proxy may redirect to an HTTPS name this machine can't resolve yet.
    if docker exec wifi-portal python -c "import urllib.request as u; print(u.urlopen('http://127.0.0.1:8080/api/auth/status', timeout=2).read().decode())" 2>/dev/null \
        | grep -q '"needs_setup":false'; then
        exit 0  # an admin already exists
    fi
    i=$((i + 1))
    sleep 1
done
if [ -e "$data/setup-code.txt" ]; then
    echo
    echo "First time? Open http://localhost and enter this setup code: $(cat "$data/setup-code.txt")"
fi
